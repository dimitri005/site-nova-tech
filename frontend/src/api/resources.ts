import { apiDownload, apiGet, apiSend } from './client'
import type { ActivityRecord, AdminUserRecord, ArticleRecord, ContactRecord, DashboardRecord, MediaRecord, NewsletterRecord, PartnerRecord, ProjectRecord, QuoteRecord, ServiceRecord, StaticPageRecord, TeamRecord, TestimonialRecord, TrainingEnrollmentRecord, TrainingRecord, TrainingSessionRecord } from './types'

export const publicApi = {
  services: (signal?: AbortSignal) => apiGet<ServiceRecord[]>('/services', signal),
  service: (slug: string, signal?: AbortSignal) => apiGet<ServiceRecord>(`/services/${encodeURIComponent(slug)}`, signal),
  projects: (signal?: AbortSignal) => apiGet<ProjectRecord[]>('/projects', signal),
  project: (slug: string, signal?: AbortSignal) => apiGet<ProjectRecord>(`/projects/${encodeURIComponent(slug)}`, signal),
  trainings: (signal?: AbortSignal) => apiGet<TrainingRecord[]>('/trainings', signal),
  training: (slug: string, signal?: AbortSignal) => apiGet<TrainingRecord>(`/trainings/${encodeURIComponent(slug)}`, signal),
  sessions: (slug: string, signal?: AbortSignal) => apiGet<TrainingSessionRecord[]>(`/trainings/${encodeURIComponent(slug)}/sessions`, signal),
  team: (signal?: AbortSignal) => apiGet<TeamRecord[]>('/team', signal),
  testimonials: (signal?: AbortSignal) => apiGet<TestimonialRecord[]>('/testimonials', signal),
  partners: (signal?: AbortSignal) => apiGet<PartnerRecord[]>('/partners', signal),
  articles: (signal?: AbortSignal) => apiGet<ArticleRecord[]>('/articles', signal),
  article: (slug: string, signal?: AbortSignal) => apiGet<ArticleRecord>(`/articles/${encodeURIComponent(slug)}`, signal),
  pages: (signal?: AbortSignal) => apiGet<StaticPageRecord[]>('/site-content/pages', signal),
  page: (slug: string, signal?: AbortSignal) => apiGet<StaticPageRecord>(`/site-content/pages/${encodeURIComponent(slug)}`, signal),
  settings: (signal?: AbortSignal) => apiGet<Record<string, string>>('/settings/public', signal),
  contact: (body: unknown) => apiSend('/contact-messages', 'POST', body),
  quote: (body: unknown) => apiSend('/quote-requests', 'POST', body),
  enroll: (body: unknown) => apiSend('/enrollments', 'POST', body),
  unsubscribe: (token: string) => apiSend(`/newsletter/unsubscribe?token=${encodeURIComponent(token)}`, 'POST'),
}

export const adminApi = {
  dashboard: () => apiGet<DashboardRecord>('/admin/dashboard'),
  services: () => apiGet<ServiceRecord[]>('/admin/services'),
  projects: () => apiGet<ProjectRecord[]>('/admin/projects'),
  trainings: () => apiGet<TrainingRecord[]>('/admin/trainings'),
  sessions: (courseId: string) => apiGet<TrainingSessionRecord[]>(`/admin/trainings/${encodeURIComponent(courseId)}/sessions`),
  team: () => apiGet<TeamRecord[]>('/admin/team'),
  testimonials: () => apiGet<TestimonialRecord[]>('/admin/testimonials'),
  partners: () => apiGet<PartnerRecord[]>('/admin/partners'),
  articles: () => apiGet<ArticleRecord[]>('/admin/articles'),
  pages: () => apiGet<StaticPageRecord[]>('/admin/site-content/pages'),
  messages: () => apiGet<ContactRecord[]>('/admin/contact-messages'),
  quotes: () => apiGet<QuoteRecord[]>('/admin/quote-requests'),
  enrollments: (sessionId: string) => apiGet<TrainingEnrollmentRecord[]>(`/admin/enrollments?sessionId=${encodeURIComponent(sessionId)}`),
  newsletter: () => apiGet<NewsletterRecord[]>('/admin/newsletter/subscribers'),
  activity: () => apiGet<ActivityRecord[]>('/admin/activity'),
  users: () => apiGet<AdminUserRecord[]>('/admin/users'),
  media: () => apiGet<MediaRecord[]>('/admin/media'),
  settings: () => apiGet<Record<string, string>>('/admin/settings'),
  exportEnrollments: (sessionId: string) => apiDownload(`/admin/enrollments/export?sessionId=${encodeURIComponent(sessionId)}`, `pre-inscriptions-${sessionId}.csv`),
  exportNewsletter: () => apiDownload('/admin/newsletter/subscribers/export', 'newsletter.csv'),
}
